import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { loadExternalProtectedCandidate } from './backend-exam-publication/external-content-package.mjs';
import { validateExamOperationsCandidate, EXAM_OPERATIONS_VALIDATOR_VERSION } from './backend-exam-publication/exam-operations-candidate.mjs';
const root = process.argv[2];
if (!root) throw Error('EXPLICIT_PRIVATE_CANDIDATE_ROOT_REQUIRED');
const privateHead = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8', windowsHide: true }).trim();
const applicationDirty = execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8', windowsHide: true }).trim() !== '';
assert.equal(privateHead, 'a900145904af9f187c80e8c8fb8a3446f011886b', 'EXACT_PRIVATE_CANDIDATE_REQUIRED');
assert.equal(execFileSync('git', ['-C', root, 'status', '--porcelain'], { encoding: 'utf8', windowsHide: true }).trim(), '', 'CLEAN_PRIVATE_CANDIDATE_REQUIRED');
const { contract } = await loadExternalProtectedCandidate(root, { examKey: 'inf303', packageVersion: '1.2.0' });
assert.equal(contract.profiles.find(p => p.profileKey === 'inf303-standard').timeLimitMinutes, 45);
assert.equal(contract.profiles.find(p => p.profileKey === 'inf303-compact').timeLimitMinutes, 60);
assert.deepEqual(contract.profiles.map(p => p.questionCount), [40, 20]);
const full = structuredClone(contract);
full.profiles = full.profiles.filter(p => p.profileKey === 'inf303-standard');
full.canonicalForms.profiles = full.canonicalForms.profiles.filter(p => p.profileKey === 'inf303-standard');
const fullResult = validateExamOperationsCandidate(full);
assert.equal(fullResult.ok, true, 'Full-only diagnostic must pass unchanged integrity checks');
const result = validateExamOperationsCandidate(contract);
assert.equal(result.ok, true, 'COMPLETE_FULL_COMPACT_PREFLIGHT_REQUIRED');
assert.equal(result.migrationClassification, 'CONTENT_RELEASE_NO_MIGRATION_EXPECTED');
assert.deepEqual(result.validation.errors, []);
assert.deepEqual(validateExamOperationsCandidate(contract), result);
const changedLength = structuredClone(full);
changedLength.profiles[0].selection.canonicalForms.forms[0].questionIds?.pop();
// Deliberately changing the scalar cannot authorize a shorter existing form.
changedLength.profiles[0].questionCount = 39;
assert.equal(validateExamOperationsCandidate(changedLength).ok, false);
console.log(JSON.stringify({ suite: 'python-fidelity-private-candidate', applicationHead: execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8', windowsHide: true }).trim(), applicationDirty, privateHead, validator: EXAM_OPERATIONS_VALIDATOR_VERSION, answeringMinutes: 45, topLevelCounts: [40,20], fullOnlyDiagnostic: 'valid', completeCandidate: 'valid', variableLengthWithinProfile: 'unsupported', protectedOutput: false }));
